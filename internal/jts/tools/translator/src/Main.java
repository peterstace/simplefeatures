import com.sun.tools.javac.api.JavacTaskImpl;
import com.sun.tools.javac.api.JavacTool;
import com.sun.tools.javac.code.Symbol.MethodSymbol;
import com.sun.tools.javac.tree.JCTree.JCCompilationUnit;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;
import java.util.stream.Stream;
import javax.tools.Diagnostic;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaFileObject;
import javax.tools.StandardJavaFileManager;

/**
 * Translates JTS core to Go.
 *
 * <p>Usage: Main --jts DIR --classpath CP --out DIR --reports DIR, where --jts is
 * JTS's modules/core/src directory and --out is the Go package directory.
 */
public final class Main {
    static final String HEADER = "// Code generated by the JTS translator. DO NOT EDIT.";

    /** Java source directories (relative to the main or test root) that are not translated. */
    private static final List<String> EXCLUDED = List.of(
            "org/locationtech/jts/awt/", "org/locationtech/jts/io/gml2/", "org/locationtech/jts/io/kml/",
            // Performance tests and tests of known failures, which JTS's
            // build does not run either.
            "test/jts/perf/", "test/jts/fail/");

    public static void main(String[] args) throws Exception {
        Map<String, String> opts = new HashMap<>();
        for (int i = 0; i + 1 < args.length; i += 2) {
            opts.put(args[i], args[i + 1]);
        }
        Path jts = Path.of(opts.get("--jts"));
        Path out = Path.of(opts.get("--out"));
        Path reports = opts.containsKey("--reports") ? Path.of(opts.get("--reports")) : null;
        String classpath = opts.get("--classpath");

        Path mainRoot = jts.resolve("main/java");
        Path testRoot = jts.resolve("test/java");
        List<Path> files = new ArrayList<>();
        files.addAll(javaFiles(mainRoot));
        files.addAll(javaFiles(testRoot));

        JavacTool tool = JavacTool.create();
        DiagnosticCollector<JavaFileObject> diags = new DiagnosticCollector<>();
        StandardJavaFileManager fm = tool.getStandardFileManager(diags, null, StandardCharsets.UTF_8);
        List<String> jopts = List.of("--release", "8", "-proc:none", "-encoding", "UTF-8", "-classpath",
                classpath, "-nowarn", "-Xlint:none", "-XDshould-stop.ifNoError=FLOW");
        JavacTaskImpl task = (JavacTaskImpl) tool.getTask(null, fm, diags, jopts, null,
                fm.getJavaFileObjectsFromPaths(files));
        List<JCCompilationUnit> units = new ArrayList<>();
        for (var u : task.parse()) {
            units.add((JCCompilationUnit) u);
        }
        task.analyze();
        boolean failed = false;
        for (Diagnostic<? extends JavaFileObject> d : diags.getDiagnostics()) {
            if (d.getKind() == Diagnostic.Kind.ERROR) {
                System.err.println(d);
                failed = true;
            }
        }
        if (failed) {
            System.exit(1);
        }

        Model model = new Model(task.getContext());
        Map<JCCompilationUnit, Path> relPaths = new LinkedHashMap<>();
        for (JCCompilationUnit u : units) {
            Path p = Path.of(u.getSourceFile().toUri());
            boolean test = p.startsWith(testRoot);
            Path rel = (test ? testRoot : mainRoot).relativize(p);
            boolean excluded = EXCLUDED.stream().anyMatch(e -> rel.toString().startsWith(e));
            model.addUnit(u, !excluded, test);
            relPaths.put(u, rel);
        }
        Runtime rt = Runtime.scan(out.resolve("java"), out.resolve("junit"));
        model.runtimeInterfaceHas = (c, n) -> {
            String q = Runtime.qualifiedName(c);
            return q != null && rt.hasMethod(q, n);
        };
        model.build();
        Translator tr = new Translator(model, rt);
        if (opts.containsKey("--api-report")) {
            tr.lenient = true;
            for (Model.ClassInfo c : model.classes.values()) {
                if (c.emitted) {
                    tr.emittingTest = Model.inTestFile(c);
                    new ClassEmitter(tr).emit(c);
                }
            }
            StringBuilder sb = new StringBuilder();
            for (Map.Entry<String, int[]> e : tr.runtimeRefs.entrySet()) {
                sb.append(e.getValue()[1] == 1 ? "ok      " : "MISSING ")
                        .append(String.format("%6d ", e.getValue()[0])).append(e.getKey()).append('\n');
            }
            Files.writeString(Path.of(opts.get("--api-report")), sb.toString());
            return;
        }

        deleteGenerated(out);
        Map<JCCompilationUnit, List<Model.ClassInfo>> byUnit = new LinkedHashMap<>();
        for (Model.ClassInfo c : model.classes.values()) {
            if (c.emitted) {
                byUnit.computeIfAbsent(model.unitOf.get(c.sym), k -> new ArrayList<>()).add(c);
            }
        }
        StringBuilder layout = new StringBuilder();
        for (Map.Entry<JCCompilationUnit, List<Model.ClassInfo>> e : byUnit.entrySet()) {
            Path rel = relPaths.get(e.getKey());
            StringBuilder mainBody = new StringBuilder();
            StringBuilder testBody = new StringBuilder();
            for (Model.ClassInfo c : e.getValue()) {
                boolean test = Model.inTestFile(c);
                tr.emittingTest = test;
                ClassEmitter ce = new ClassEmitter(tr);
                ce.emit(c);
                (test ? testBody : mainBody).append(ce.text()).append('\n');
                if (c.superInfo != null || c.rtSuper != null && rt.hasType(Runtime.qualifiedName(c.rtSuper))) {
                    String field = c.superInfo != null ? c.superInfo.goName : c.rtSuper.name.toString();
                    layout.append("if unsafe.Offsetof(").append(c.goName).append("{}.").append(field)
                            .append(") != 0 { t.Error(\"").append(c.goName).append("\") }\n");
                }
            }
            String pkg = e.getKey().getPackageName().toString();
            String base = Model.pkgPrefix(pkg) + "_" + rel.getFileName().toString().replace(".java", "");
            if (mainBody.length() > 0) {
                write(out.resolve(base + ".go"), mainBody.toString());
            }
            if (testBody.length() > 0) {
                write(out.resolve(base + "_test.go"), testBody.toString());
            }
        }
        StringBuilder lambdas = new StringBuilder();
        for (Model.ClassInfo c : tr.lambdaInterfaces) {
            MethodSymbol desc = (MethodSymbol) model.types.findDescriptorSymbol(c.sym);
            com.sun.tools.javac.code.Type sig = tr.goSignature(desc);
            StringBuilder params = new StringBuilder();
            StringBuilder callArgs = new StringBuilder();
            int i = 0;
            for (com.sun.tools.javac.code.Type p : sig.getParameterTypes()) {
                params.append(i > 0 ? ", " : "").append("a").append(i).append(' ').append(tr.goType(p));
                callArgs.append(i > 0 ? ", " : "").append("a").append(i);
                i++;
            }
            com.sun.tools.javac.code.Type r = sig.getReturnType();
            String ret = r.hasTag(com.sun.tools.javac.code.TypeTag.VOID) ? "" : " " + tr.goType(r);
            String fn = c.goName + "_jfunc";
            lambdas.append("// ").append(fn).append(" adapts a function literal to ").append(c.goName).append(".\n");
            lambdas.append("type ").append(fn).append(" func(").append(params).append(")").append(ret).append("\n\n");
            lambdas.append("func (f ").append(fn).append(") ").append(model.instanceMethodName(desc)).append("(")
                    .append(params).append(")").append(ret).append(" { ").append(ret.isEmpty() ? "" : "return ")
                    .append("f(").append(callArgs).append(") }\n");
            for (com.sun.tools.javac.code.Type it : model.types.closure(c.sym.type)) {
                if (model.isJts(it.tsym)) {
                    lambdas.append("func (f ").append(fn).append(") JIface_").append(model.info(it.tsym).goName)
                            .append("() {}\n");
                }
            }
            lambdas.append('\n');
        }
        write(out.resolve("jts_lambdas.go"), lambdas.toString());
        StringBuilder lits = new StringBuilder();
        for (Map.Entry<String, Integer> e : tr.literals.entrySet()) {
            lits.append("var jlit_").append(e.getValue()).append(" = java.Lit(")
                    .append(Translator.goQuote(e.getKey())).append(")\n");
        }
        write(out.resolve("jts_strings.go"), lits.toString());
        write(out.resolve("jts_layout_test.go"),
                "func TestLayout(t *testing.T) {\n" + layout + "}\n\n"
                        + "func TestStaticInit(t *testing.T) {\nfor _, f := range java.StaticInitFailures {\nt.Error(f)\n}\n}\n");

        writeReports(tr, reports);

        List<String> gofmt = new ArrayList<>(List.of("gofmt", "-w"));
        gofmt.addAll(WRITTEN);
        Process p = new ProcessBuilder(gofmt).inheritIO().start();
        if (p.waitFor() != 0) {
            System.exit(1);
        }
    }

    private static List<Path> javaFiles(Path root) throws IOException {
        try (Stream<Path> s = Files.walk(root)) {
            return s.filter(p -> p.toString().endsWith(".java")).sorted().toList();
        }
    }

    private static void deleteGenerated(Path dir) throws IOException {
        try (Stream<Path> s = Files.list(dir)) {
            for (Path p : s.filter(p -> p.toString().endsWith(".go")).toList()) {
                List<String> lines = Files.readAllLines(p);
                if (!lines.isEmpty() && lines.get(0).equals(HEADER)) {
                    Files.delete(p);
                }
            }
        }
    }

    private static final Map<String, Pattern> IMPORTS = new LinkedHashMap<>();

    static {
        for (String pkg : List.of("math", "sync", "testing", "unsafe")) {
            IMPORTS.put(pkg, Pattern.compile("(?<![\\w.\"])" + pkg + "\\."));
        }
        IMPORTS.put("github.com/peterstace/simplefeatures/internal/jts/java",
                Pattern.compile("(?<![\\w.\"])java\\."));
        IMPORTS.put("github.com/peterstace/simplefeatures/internal/jts/junit",
                Pattern.compile("(?<![\\w.\"])junit\\."));
    }

    /** Files written by this run, which are the only files formatted. */
    private static final List<String> WRITTEN = new ArrayList<>();

    private static void write(Path file, String body) throws IOException {
        WRITTEN.add(file.toString());
        StringBuilder sb = new StringBuilder(HEADER).append("\n\npackage jts\n\n");
        List<String> imports = new ArrayList<>();
        String code = stripStrings(body);
        for (Map.Entry<String, Pattern> e : IMPORTS.entrySet()) {
            if (e.getValue().matcher(code).find()) {
                imports.add(e.getKey());
            }
        }
        if (!imports.isEmpty()) {
            sb.append("import (\n");
            for (String i : imports) {
                sb.append('\t').append('"').append(i).append("\"\n");
            }
            sb.append(")\n\n");
        }
        sb.append(body);
        Files.writeString(file, sb.toString());
    }

    /** Removes Go string literal contents and comments so import detection only sees code. */
    private static String stripStrings(String s) {
        return s.replaceAll("\"(?:[^\"\\\\\\n]|\\\\.)*\"", "\"\"").replaceAll("//[^\\n]*", "");
    }

    private static void writeReports(Translator tr, Path dir) throws IOException {
        Files.createDirectories(dir);
        StringBuilder sb = new StringBuilder("# Translation Report\n\n");
        int total = tr.unsupported.values().stream().mapToInt(List::size).sum();
        sb.append("Stubbed members: ").append(total).append("\n\n");
        List<Map.Entry<String, List<String>>> entries = new ArrayList<>(tr.unsupported.entrySet());
        entries.sort((a, b) -> b.getValue().size() - a.getValue().size());
        sb.append("| Count | Reason |\n| ----- | ------ |\n");
        for (Map.Entry<String, List<String>> e : entries) {
            sb.append("| ").append(e.getValue().size()).append(" | ").append(e.getKey().replace("|", "\\|"))
                    .append(" |\n");
        }
        sb.append("\n## Details\n");
        for (Map.Entry<String, List<String>> e : entries) {
            sb.append("\n### ").append(e.getKey()).append("\n\n");
            for (String w : e.getValue()) {
                sb.append("- ").append(w).append('\n');
            }
        }
        Files.writeString(dir.resolve("REPORT.md"), sb.toString());

    }
}
