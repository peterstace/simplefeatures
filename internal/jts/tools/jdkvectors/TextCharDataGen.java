/*
 * TextCharDataGen writes internal/jts/java/text_chardata.go, the Unicode
 * character tables behind the Go implementation of java.lang.Character and
 * of String case conversion. The tables come from the running JDK (Unicode
 * 15.0 for JDK 21), so that the Go runtime does not depend on the Unicode
 * version of the Go toolchain. Regenerate from the repository root with:
 *
 *   java --add-exports java.base/jdk.internal.icu.lang=ALL-UNNAMED \
 *       internal/jts/tools/jdkvectors/TextCharDataGen.java > internal/jts/java/text_chardata.go
 *   gofmt -w internal/jts/java/text_chardata.go
 *
 * The export gives access to the canonical combining classes, which
 * String's locale-sensitive case conversion consults.
 */

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

public class TextCharDataGen {
    static final int MAX = Character.MAX_CODE_POINT;

    public static void main(String[] args) throws Exception {
        java.lang.reflect.Method ccc = Class.forName("jdk.internal.icu.lang.UCharacter")
                .getMethod("getCombiningClass", int.class);
        StringBuilder out = new StringBuilder();
        out.append("// Code generated by internal/jts/tools/jdkvectors/TextCharDataGen.java from JDK ")
                .append(System.getProperty("java.specification.version")).append("; DO NOT EDIT.\n\n");
        out.append("package java\n\n");

        // General category runs.
        out.append("// charTypeRuns holds the general category (Character.getType) of every\n");
        out.append("// code point as runs: each entry is start<<5 | type, and the run extends\n");
        out.append("// to the next entry's start. It is a read-only lookup table.\n");
        out.append("var charTypeRuns = [...]uint32{\n");
        int prev = -1;
        int n = 0;
        for (int cp = 0; cp <= MAX; cp++) {
            int t = Character.getType(cp);
            if (t != prev) {
                out.append(String.format("0x%x,", (cp << 5) | t));
                if (++n % 8 == 0) {
                    out.append('\n');
                } else {
                    out.append(' ');
                }
                prev = t;
            }
        }
        out.append("\n}\n\n");

        caseRuns(out, "charUpperRuns", "Character.toUpperCase", 0);
        caseRuns(out, "charLowerRuns", "Character.toLowerCase", 1);
        titleRuns(out);

        // Digit values.
        out.append("// charDigitRuns maps code points to Character.digit(cp, 36): within the\n");
        out.append("// run {start, end, value} the code point start+i has digit value value+i.\n");
        out.append("// It is a read-only lookup table.\n");
        out.append("var charDigitRuns = [...][3]int32{\n");
        int cp = 0;
        while (cp <= MAX) {
            int v = Character.digit(cp, 36);
            if (v < 0) {
                cp++;
                continue;
            }
            int start = cp;
            while (cp + 1 <= MAX && Character.digit(cp + 1, 36) == v + (cp + 1 - start)) {
                cp++;
            }
            out.append(String.format("{0x%x, 0x%x, %d},\n", start, cp, v));
            cp++;
        }
        out.append("}\n\n");

        ranges(out, "charOtherLowerRanges",
                "code points for which Character.isLowerCase is true but whose type is not\n// LOWERCASE_LETTER",
                c -> Character.isLowerCase(c) && Character.getType(c) != Character.LOWERCASE_LETTER);
        ranges(out, "charOtherUpperRanges",
                "code points for which Character.isUpperCase is true but whose type is not\n// UPPERCASE_LETTER",
                c -> Character.isUpperCase(c) && Character.getType(c) != Character.UPPERCASE_LETTER);
        ranges(out, "charOtherAlphabeticRanges",
                "code points for which Character.isAlphabetic is true but whose type is not\n// a letter or LETTER_NUMBER",
                c -> Character.isAlphabetic(c) && !isLetterOrNl(c));
        ranges(out, "charIdeographicRanges", "code points for which Character.isIdeographic is true",
                Character::isIdeographic);

        ranges(out, "charCombiningAboveRanges", "code points whose canonical combining class is 230 (Above)",
                c -> combiningClass(ccc, c) == 230);
        ranges(out, "charCombiningOtherRanges",
                "code points whose canonical combining class is neither 0 nor 230",
                c -> combiningClass(ccc, c) != 0 && combiningClass(ccc, c) != 230);

        // Full upper case mappings of single code points (String.toUpperCase).
        out.append("// charSpecialUpper maps the code points whose String.toUpperCase(Locale.ROOT)\n");
        out.append("// is not the single code point Character.toUpperCase to their full upper case\n");
        out.append("// mapping. It is a read-only lookup table.\n");
        out.append("var charSpecialUpper = map[int32]string{\n");
        for (cp = 0; cp <= MAX; cp++) {
            if (cp >= Character.MIN_SURROGATE && cp <= Character.MAX_SURROGATE) {
                continue;
            }
            String s = new String(Character.toChars(cp));
            String up = s.toUpperCase(Locale.ROOT);
            String simple = new String(Character.toChars(Character.toUpperCase(cp)));
            if (!up.equals(simple)) {
                out.append(String.format("0x%x: \"%s\",\n", cp, goEscape(up)));
            }
        }
        out.append("}\n");
        System.out.print(out);
    }

    static int combiningClass(java.lang.reflect.Method ccc, int c) {
        try {
            return (Integer) ccc.invoke(null, c);
        } catch (ReflectiveOperationException e) {
            throw new RuntimeException(e);
        }
    }

    static boolean isLetterOrNl(int c) {
        int t = Character.getType(c);
        return t == Character.UPPERCASE_LETTER || t == Character.LOWERCASE_LETTER
                || t == Character.TITLECASE_LETTER || t == Character.MODIFIER_LETTER
                || t == Character.OTHER_LETTER || t == Character.LETTER_NUMBER;
    }

    interface Prop {
        boolean test(int cp);
    }

    static void ranges(StringBuilder out, String name, String what, Prop p) {
        out.append("// ").append(name).append(" lists, as inclusive {start, end} ranges, the\n");
        out.append("// ").append(what).append(". It is a read-only lookup table.\n");
        out.append("var ").append(name).append(" = [...][2]int32{\n");
        int cp = 0;
        while (cp <= MAX) {
            if (!p.test(cp)) {
                cp++;
                continue;
            }
            int start = cp;
            while (cp + 1 <= MAX && p.test(cp + 1)) {
                cp++;
            }
            out.append(String.format("{0x%x, 0x%x},\n", start, cp));
            cp++;
        }
        out.append("}\n\n");
    }

    static int map(int kind, int cp) {
        return kind == 0 ? Character.toUpperCase(cp) : Character.toLowerCase(cp);
    }

    // titleRuns writes the code points whose title case differs from their
    // upper case, as runs {start, end, delta} of consecutive code points
    // whose title case is themselves plus delta.
    static void titleRuns(StringBuilder out) {
        out.append("// charTitleRuns lists, as runs {start, end, delta}, the code points whose\n");
        out.append("// Character.toTitleCase differs from Character.toUpperCase; their title case\n");
        out.append("// is the code point plus delta. It is a read-only lookup table.\n");
        out.append("var charTitleRuns = [...][3]int32{\n");
        int cp = 0;
        while (cp <= MAX) {
            if (Character.toTitleCase(cp) == Character.toUpperCase(cp)) {
                cp++;
                continue;
            }
            int d = Character.toTitleCase(cp) - cp;
            int start = cp;
            while (cp + 1 <= MAX && Character.toTitleCase(cp + 1) != Character.toUpperCase(cp + 1)
                    && Character.toTitleCase(cp + 1) - (cp + 1) == d) {
                cp++;
            }
            out.append(String.format("{0x%x, 0x%x, %d},\n", start, cp, d));
            cp++;
        }
        out.append("}\n\n");
    }

    // caseRuns writes runs {start, end, delta, step}: every code point
    // start + k*step <= end maps to itself plus delta. Code points between
    // the members of a run with step 2 map to themselves.
    static void caseRuns(StringBuilder out, String name, String what, int kind) {
        out.append("// ").append(name).append(" holds ").append(what).append(" as runs\n");
        out.append("// {start, end, delta, step}: the code points start, start+step, ... up to end\n");
        out.append("// map to themselves plus delta, and all others map to themselves. It is a\n");
        out.append("// read-only lookup table.\n");
        out.append("var ").append(name).append(" = [...][4]int32{\n");
        int cp = 0;
        while (cp <= MAX) {
            int d = map(kind, cp) - cp;
            if (d == 0) {
                cp++;
                continue;
            }
            int start = cp;
            int end = cp;
            int step = 1;
            while (end + 1 <= MAX && map(kind, end + 1) - (end + 1) == d) {
                end++;
            }
            if (end == start) {
                while (end + 2 <= MAX && map(kind, end + 1) == end + 1 && map(kind, end + 2) - (end + 2) == d) {
                    end += 2;
                    step = 2;
                }
            }
            out.append(String.format("{0x%x, 0x%x, %d, %d},\n", start, end, d, step));
            cp = end + 1;
        }
        out.append("}\n\n");
    }

    static String goEscape(String s) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < s.length(); ) {
            int cp = s.codePointAt(i);
            i += Character.charCount(cp);
            if (cp >= 0x20 && cp < 0x7f && cp != '"' && cp != '\\') {
                sb.append((char) cp);
            } else if (cp <= 0xffff) {
                sb.append(String.format("\\u%04x", cp));
            } else {
                sb.append(String.format("\\U%08x", cp));
            }
        }
        return sb.toString();
    }
}
