/*
 * TextLocaleDataGen writes internal/jts/java/text_localedata.go, the number
 * formatting data (DecimalFormatSymbols and the number and percent patterns
 * of NumberFormat) of every locale that the running JDK provides. Regenerate
 * from the repository root with:
 *
 *   java internal/jts/tools/jdkvectors/TextLocaleDataGen.java > internal/jts/java/text_localedata.go
 *   gofmt -w internal/jts/java/text_localedata.go
 */

import java.text.DecimalFormat;
import java.text.DecimalFormatSymbols;
import java.text.NumberFormat;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;

public class TextLocaleDataGen {
    public static void main(String[] args) {
        Map<String, Integer> sets = new LinkedHashMap<>();
        Map<String, Integer> index = new TreeMap<>();
        // The root locale first, so that it has index 0.
        List<Locale> locales = new ArrayList<>();
        locales.add(Locale.ROOT);
        // getAvailableLocales has no fixed order; sort for deterministic
        // output.
        List<Locale> available = new ArrayList<>(List.of(NumberFormat.getAvailableLocales()));
        available.sort((a, b) -> a.toLanguageTag().compareTo(b.toLanguageTag()));
        for (Locale l : available) {
            if (!l.equals(Locale.ROOT)) {
                locales.add(l);
            }
        }
        for (Locale l : locales) {
            DecimalFormatSymbols s = DecimalFormatSymbols.getInstance(l);
            DecimalFormat nf = (DecimalFormat) NumberFormat.getNumberInstance(l);
            DecimalFormat pf = (DecimalFormat) NumberFormat.getPercentInstance(l);
            String entry = "{"
                    + "zero: " + ch(s.getZeroDigit())
                    + ", grouping: " + ch(s.getGroupingSeparator())
                    + ", decimal: " + ch(s.getDecimalSeparator())
                    + ", perMill: " + ch(s.getPerMill())
                    + ", percent: " + ch(s.getPercent())
                    + ", digit: " + ch(s.getDigit())
                    + ", patternSeparator: " + ch(s.getPatternSeparator())
                    + ", minus: " + ch(s.getMinusSign())
                    + ", monetaryDecimal: " + ch(s.getMonetaryDecimalSeparator())
                    + ", monetaryGrouping: " + ch(s.getMonetaryGroupingSeparator())
                    + ", exponent: " + str(s.getExponentSeparator())
                    + ", infinity: " + str(s.getInfinity())
                    + ", nan: " + str(s.getNaN())
                    + ", percentText: " + str(percentText(l, s))
                    + ", perMillText: " + str(perMillText(l, s))
                    + ", minusText: " + str(minusText(l, s))
                    + ", numberPattern: " + str(nf.toPattern())
                    + ", percentPattern: " + str(pf.toPattern())
                    + "}";
            Integer i = sets.get(entry);
            if (i == null) {
                i = sets.size();
                sets.put(entry, i);
            }
            index.put(l.toLanguageTag(), i);
        }
        StringBuilder out = new StringBuilder();
        out.append("// Code generated by internal/jts/tools/jdkvectors/TextLocaleDataGen.java from JDK ")
                .append(System.getProperty("java.specification.version")).append("; DO NOT EDIT.\n\n");
        out.append("package java\n\n");
        out.append("// localeNumberDataSets holds the distinct number formatting data of the\n");
        out.append("// JDK's locales. It is a read-only lookup table.\n");
        out.append("var localeNumberDataSets = [...]localeNumberData{\n");
        for (String e : sets.keySet()) {
            out.append(e).append(",\n");
        }
        out.append("}\n\n");
        out.append("// localeNumberDataIndex maps the language tag of each JDK locale to its\n");
        out.append("// entry in localeNumberDataSets. It is a read-only lookup table.\n");
        out.append("var localeNumberDataIndex = map[string]uint8{\n");
        for (Map.Entry<String, Integer> e : index.entrySet()) {
            out.append(str(e.getKey())).append(": ").append(e.getValue()).append(",\n");
        }
        out.append("}\n");
        System.out.print(out);
    }

    // The *Text symbols are package-private in the JDK; they are recovered
    // from a formatted value.
    static String percentText(Locale l, DecimalFormatSymbols s) {
        DecimalFormat f = new DecimalFormat("0'X'%", s);
        String r = f.format(0);
        return r.substring(r.indexOf('X') + 1);
    }

    static String perMillText(Locale l, DecimalFormatSymbols s) {
        DecimalFormat f = new DecimalFormat("0'X'‰", s);
        String r = f.format(0);
        return r.substring(r.indexOf('X') + 1);
    }

    static String minusText(Locale l, DecimalFormatSymbols s) {
        DecimalFormat f = new DecimalFormat("0", s);
        String r = f.format(-1);
        return r.substring(0, r.length() - 1);
    }

    static String ch(char c) {
        if (c >= 0x20 && c < 0x7f && c != '\'' && c != '\\') {
            return "'" + c + "'";
        }
        return String.format("0x%04x", (int) c);
    }

    static String str(String s) {
        StringBuilder sb = new StringBuilder("\"");
        for (int i = 0; i < s.length(); ) {
            int cp = s.codePointAt(i);
            i += Character.charCount(cp);
            if (cp >= 0x20 && cp < 0x7f && cp != '"' && cp != '\\') {
                sb.append((char) cp);
            } else if (cp <= 0xffff) {
                sb.append(String.format("\\u%04x", cp));
            } else {
                sb.append(String.format("\\U%08x", cp));
            }
        }
        return sb.append('"').toString();
    }
}
