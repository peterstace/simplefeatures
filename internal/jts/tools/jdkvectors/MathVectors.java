/*
 * MathVectors prints test vectors for the Go implementation of
 * java.lang.Math and java.lang.StrictMath in internal/jts/java (math.go and
 * fdlibm.go). Regenerate the vectors from the repository root with:
 *
 *   java internal/jts/tools/jdkvectors/MathVectors.java > internal/jts/java/testdata/math.txt
 *
 * An optional integer argument multiplies the number of random inputs per
 * function, for a more thorough local check against a temporary file; the
 * committed file uses the default of 1.
 *
 * The output has a section per function, headed "[<name>]", where <name> is
 * the Go function name without its Math_ or StrictMath_ prefix. Each line in a
 * section is "<arg>... <result>". Doubles and floats are written as their raw
 * IEEE 754 bits in hex (16 and 8 digits), ints and longs in decimal, and a
 * thrown ArithmeticException as "ArithmeticException".
 *
 * Expected results come from StrictMath where StrictMath has the method (it is
 * fully specified as fdlibm), and from Math otherwise. Math is also evaluated,
 * and any input where Math and StrictMath disagree is counted on stderr: the
 * JIT's intrinsics make them differ for some functions unless the JVM runs
 * with -XX:+UnlockDiagnosticVMOptions -XX:-InlineMathNatives.
 *
 * The program uses java.util.Random with fixed seeds, so its output is
 * deterministic.
 */

