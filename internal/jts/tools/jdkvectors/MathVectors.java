    interface IntCall { int call(); }
    interface LongCall { long call(); }

    static String callI(IntCall c) {
        try {
            return Integer.toString(c.call());
        } catch (ArithmeticException e) {
            return EXC;
        }
    }

    static String callL(LongCall c) {
        try {
            return Long.toString(c.call());
        } catch (ArithmeticException e) {
            return EXC;
        }
    }
