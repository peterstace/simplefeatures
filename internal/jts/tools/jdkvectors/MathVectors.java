    // addThresholds adds, for each high word h (as fdlibm compares them),
    // both signs of the doubles at and around the boundary it marks.
    static void addThresholds(List<Double> in, int... highs) {
        for (int h : highs) {
            int abs = h & 0x7fffffff;
            for (double v : new double[] {hiLo(abs, 0), hiLo(abs, 1), hiLo(abs, 0xffffffff),
                hiLo(abs - 1, 0xffffffff), hiLo(abs + 1, 0)}) {
                in.add(v);
                in.add(-v);
            }
        }
    }

    static void addNearby(List<Double> in, double v, int ulps) {
        for (int i = -ulps; i <= ulps; i++) {
            in.add(Double.longBitsToDouble(Double.doubleToRawLongBits(v) + i));
        }
    }

    static void addNearbyF(List<Float> in, float v, int ulps) {
        for (int i = -ulps; i <= ulps; i++) {
            in.add(Float.intBitsToFloat(Float.floatToRawIntBits(v) + i));
        }
    }

    static void cross(List<double[]> pairs, double[] as, double[] bs) {
        for (double a : as) {
            for (double b : bs) {
                pairs.add(new double[] {a, b});
            }
        }
    }

    static double hiLo(int hi, int lo) {
        return Double.longBitsToDouble(((long) hi << 32) | (lo & 0xffffffffL));
    }

    static double randBits(Random r) {
        return Double.longBitsToDouble(r.nextLong());
    }

    // randExp returns a value of random sign and significand whose binary
    // exponent is uniform in [lo, hi]; exponents below -1022 give subnormals.
    static double randExp(Random r, int lo, int hi) {
        int e = lo + r.nextInt(hi - lo + 1);
        long signif = r.nextLong() & 0xfffffffffffffL;
        double v;
        if (e >= -1022) {
            v = Double.longBitsToDouble(((long) (e + 1023) << 52) | signif);
        } else {
            v = Double.longBitsToDouble((signif | (1L << 52)) >>> (-1022 - e));
        }
        return r.nextBoolean() ? -v : v;
    }

    static double uniform(Random r, double a, double b) {
        return a + (b - a) * r.nextDouble();
    }

