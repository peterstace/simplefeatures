    static String hex(double d) {
        return String.format("%016x", Double.doubleToRawLongBits(d));
    }

    static String hex(float f) {
        return String.format("%08x", Float.floatToRawIntBits(f));
    }

    static boolean same(double a, double b) {
        return Double.doubleToLongBits(a) == Double.doubleToLongBits(b);
    }

    static boolean same(float a, float b) {
        return Float.floatToIntBits(a) == Float.floatToIntBits(b);
    }

    static void mismatch(String name) {
        mismatches.merge(name, 1, Integer::sum);
    }

    static void section(String name) throws IOException {
        out.write("[" + name + "]\n");
    }

    static void line(String... fields) throws IOException {
        out.write(String.join(" ", fields));
        out.write('\n');
    }

    static void d1(String name, D1 strict, D1 math, List<Double> in) throws IOException {
        section(name);
        for (double a : in) {
            double want = strict.f(a);
            if (math != null && !same(want, math.f(a))) {
                mismatch(name);
            }
            line(hex(a), hex(want));
        }
    }

    static void d2(String name, D2 strict, D2 math, List<double[]> in) throws IOException {
        section(name);
        for (double[] p : in) {
            double want = strict.f(p[0], p[1]);
            if (math != null && !same(want, math.f(p[0], p[1]))) {
                mismatch(name);
            }
            line(hex(p[0]), hex(p[1]), hex(want));
        }
    }

    // d2math writes vectors for a Math method whose specification differs
    // from the StrictMath method of the same name; the section name has an
    // "@Math" suffix.
    static void d2math(String name, D2 math, List<double[]> in) throws IOException {
        section(name + "@Math");
        for (double[] p : in) {
            line(hex(p[0]), hex(p[1]), hex(math.f(p[0], p[1])));
        }
    }

