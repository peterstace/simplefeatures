    static void hyperbolic() throws IOException {
        String[] names = {"sinh", "cosh", "tanh"};
        D1[] strict = {StrictMath::sinh, StrictMath::cosh, StrictMath::tanh};
        D1[] math = {Math::sinh, Math::cosh, Math::tanh};
        for (int f = 0; f < names.length; f++) {
            Random r = new Random(14 + f);
            List<Double> in = specials();
            addThresholds(in, 0x40360000, 0x40862E42, 0x408633CE, 0x3e300000, 0x3c800000, 0x3fd62e43,
                0x3ff00000);
            for (double v : new double[] {hiLo(0x408633ce, 0x8fb9f87d), 710.4758600739439}) {
                addNearby(in, v, 4);
                addNearby(in, -v, 4);
            }
            for (int i = 0; i < n(500); i++) {
                in.add(uniform(r, -25, 25));
            }
            for (int i = 0; i < n(200); i++) {
                in.add(uniform(r, -720, 720));
            }
            for (int i = 0; i < n(300); i++) {
                in.add(randExp(r, -60, 10));
            }
            for (int i = 0; i < n(150); i++) {
                in.add(randBits(r));
            }
            d1(names[f], strict[f], math[f], in);
        }
    }

